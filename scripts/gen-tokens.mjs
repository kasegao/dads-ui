// Generates src/preset/tokens.generated.ts from @digital-go-jp/design-tokens (tokens.css).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const css = readFileSync(require.resolve('@digital-go-jp/design-tokens/dist/tokens.css'), 'utf8');

const vars = {};
for (const m of css.matchAll(/--([\w-]+):\s*([^;]+);/g)) vars[m[1]] = m[2].trim();

const colors = {};
const set = (group, step, value) => {
  colors[group] ??= {};
  colors[group][step] = { value };
};
const semantic = {};
const fontSizes = {};
const lineHeights = {};
const radii = {};
const shadows = {};

const primitiveRef = (value) => {
  const ref = value.match(/--color-primitive-(.+)-(\d+)\)/);
  return `{colors.${ref[1]}.${ref[2]}}`;
};

/** [pattern, handler] pairs; the first matching pattern wins. */
const rules = [
  [/^color-primitive-(.+)-(\d+)$/, (m, value) => set(m[1], m[2], value)],
  [/^color-neutral-(solid-gray|opacity-gray)-(\d+)$/, (m, value) => set(m[1], m[2], value)],
  [
    /^color-neutral-(white|black)$/,
    (m, value) => {
      colors[m[1]] = { value };
    },
  ],
  [
    /^color-key-(\d+)$/,
    (m, value) => {
      semantic.key ??= {};
      semantic.key[m[1]] = { value: primitiveRef(value) };
    },
  ],
  [
    /^color-semantic-(.+)-(\d)$/,
    (m, value) => {
      semantic[m[1]] ??= {};
      semantic[m[1]][m[2]] = { value: primitiveRef(value) };
    },
  ],
  [
    /^font-size-(\d+)$/,
    (m, value) => {
      fontSizes[m[1]] = { value };
    },
  ],
  [
    /^line-height-(\d+)$/,
    (m, value) => {
      lineHeights[m[1]] = { value };
    },
  ],
  [
    /^border-radius-(.+)$/,
    (m, value) => {
      radii[m[1]] = { value };
    },
  ],
  [
    /^elevation-(\d)$/,
    (m, value) => {
      shadows[m[1]] = { value };
    },
  ],
];

for (const [name, value] of Object.entries(vars)) {
  for (const [pattern, handler] of rules) {
    const m = name.match(pattern);
    if (m) {
      handler(m, value);
      break;
    }
  }
}

const out = `// Generated by scripts/gen-tokens.mjs from @digital-go-jp/design-tokens. Do not edit.
export const colors = ${JSON.stringify(colors, null, 2)} as const;

export const semanticColors = ${JSON.stringify(semantic, null, 2)} as const;

export const fontSizes = ${JSON.stringify(fontSizes, null, 2)} as const;

export const lineHeights = ${JSON.stringify(lineHeights, null, 2)} as const;

export const radii = ${JSON.stringify(radii, null, 2)} as const;

export const shadows = ${JSON.stringify(shadows, null, 2)} as const;
`;
writeFileSync(new URL('../src/preset/tokens.generated.ts', import.meta.url), out);
console.log(
  `colors: ${Object.keys(colors).length} groups, fontSizes: ${Object.keys(fontSizes).length}`,
);
